def gen_monster_spells(mons, mspells, projs):
    lines = ["# Appendix A3 — Monster Spells, Breaths and Damage Formulas\n",
             GEN_NOTE.format("monster_spell.txt, projection.txt"),
             "Monster spell damage depends on the caster's **spell power**, which is "
             "its native depth unless `spell-power` overrides it in `monster.txt` "
             "(`src/mon-init.c`). Breaths ignore spell power: damage is the "
             "monster's **current** HP divided by the element's divisor, capped "
             "(`breath_dam()`, `src/mon-spell.c`). A wounded breather is much less "
             "dangerous.\n",
             "## Breath table\n",
             "| Element | HP divisor | Damage cap | Resist fraction | Max-cap needs monster HP ≥ |",
             "|---|---:|---:|---|---:|"]
    for code, p in projs.items():
        if not p["divisor"]:
            continue
        if p["type"] != "element":
            continue
        frac = ("%s / (%s)" % (p["num"], p["den"])) if p["num"] else "no resist reduction"
        need = p["divisor"] * p["cap"] if p["cap"] else 0
        lines.append("| %s (`%s`) | %d | %s | %s | %s |" % (
            p["name"], code, p["divisor"], p["cap"] or "none", frac,
            need if need else "—"))
    lines.append("")
    lines.append("Resist fraction: damage is multiplied by numerator/denominator once "
                 "per level of resistance (`adjust_dam()` in `src/project-player.c`). "
                 "One permanent resistance is level 1; a timed resistance "
                 "(`OPP_ACID`, `OPP_ELEC`, `OPP_FIRE`, `OPP_COLD`, `OPP_POIS`) adds "
                 "one more level up to 2 (`src/player-calcs.c`), so acid/elec/fire/"
                 "cold/poison drop to 1/3 with one resist and 1/9 with both. "
                 "Immunity (level 3) negates the damage; vulnerability multiplies "
                 "it by 4/3. Acid damage is additionally halved if it hits a piece "
                 "of armour (`minus_ac()`). High elements use a random denominator "
                 "`8+1d4`, so a resisted breath does 6/9 to 6/12 of its raw damage. "
                 "Elements with no numerator listed (water, gravity, inertia, force, "
                 "time, plasma, mana...) cannot be resisted by damage reduction at "
                 "all.\n")

    lines.append("## Every monster spell\n")
    lines.append("| Spell | Effect(s) | Damage formula | Lore by power |")
    lines.append("|---|---|---|---|")
    for name, sp in mspells.items():
        effs = ", ".join(e["effect"] for e in sp["effects"]) or "—"
        forms = []
        for e in sp["effects"]:
            if e["dice"]:
                f = e["dice"]
                for var, (src, ops) in e["expr"].items():
                    f += " ; %s = %s %s" % (var, "power" if src == "SPELL_POWER" else src, ops)
                forms.append(f)
        if sp["effects"] and sp["effects"][0]["effect"].startswith("BREATH"):
            elem = sp["effects"][0]["effect"].split(":")[1]
            p = projs.get(elem, {})
            forms.insert(0, "HP/%s, max %s" % (p.get("divisor", "?"), p.get("cap", "?")))
        lores = []
        lo = 0
        for cutoff, lore in sp["lores"]:
            if lore is None:
                continue
            rng = "power %d+" % lo if cutoff is None else "power %d–%d" % (lo, cutoff)
            if len(sp["lores"]) == 1:
                rng = ""
            lores.append(("%s: %s" % (rng, lore)) if rng else lore)
            if cutoff is not None:
                lo = cutoff + 1
        lines.append("| `%s` | %s | %s | %s |" % (
            name, md(effs), md("; ".join(forms)) or "—", md("; ".join(lores)) or "—"))
    lines.append("")

    # Who breathes what hardest
    lines.append("## The deadliest breathers, per element\n")
    lines.append("For each breath, the ten monsters whose (average-HP) breath is the "
                 "largest, with their native depth. These numbers drive the "
                 "resistance-by-depth advice in "
                 "[Chapter 4](04-resistances-afflictions.md).\n")
    by_elem = defaultdict(list)
    for m in mons:
        for s in m["spells"]:
            if s.startswith("BR_") and s in mspells:
                d = spell_damage(mspells[s], m["power"], m["hp"], projs)
                if d:
                    by_elem[s].append((d[1], m))
    for s in sorted(by_elem):
        lst = sorted(by_elem[s], key=lambda x: (-x[0], x[1]["depth"]))[:10]
        first_m = min(by_elem[s], key=lambda x: x[1]["depth"])
        lines.append("### %s — %s\n" % (s, spell_lore(mspells[s], 0) or ""))
        lines.append("Shallowest breather: **%s** (DL%d, %d dmg). Breathers in total: %d.\n"
                     % (first_m[1]["name"], first_m[1]["depth"], first_m[0], len(by_elem[s])))
        lines.append("| Monster | DL | Spd | HP | Max breath |")
        lines.append("|---|---:|---:|---:|---:|")
        for dam, m in lst:
            lines.append("| %s%s | %d | %s | %d | %d |" % (
                md(m["name"]), " (U)" if "UNIQUE" in m["flags"] else "",
                m["depth"], fmt_speed(m["speed"]), m["hp"], dam))
        lines.append("")

    # First appearance of key threats
    lines.append("## First appearance of key threats\n")
    lines.append("The shallowest native depth at which a monster with each ability "
                 "appears (uniques included).\n")
    lines.append("| Threat | Shallowest monster | DL |")
    lines.append("|---|---|---:|")
    checks = OrderedDict()
    for s in ["HOLD", "BLIND", "CONF", "SCARE", "SLOW", "FORGET", "DRAIN_MANA",
              "TELE_TO", "TELE_AWAY", "TELE_LEVEL", "MIND_BLAST", "BRAIN_SMASH",
              "BO_MANA", "BA_MANA", "BA_NETH", "BA_DARK", "S_UNDEAD", "S_DEMON",
              "S_DRAGON", "S_HI_UNDEAD", "S_HI_DEMON", "S_HI_DRAGON", "S_UNIQUE",
              "S_WRAITH", "S_HOUND", "HEAL", "HASTE", "TRAPS", "DARKNESS"]:
        checks["casts " + s] = lambda m, s=s: s in m["spells"]
    blow_effects = ["PARALYZE", "POISON", "BLIND", "CONFUSE", "TERRIFY",
                    "LOSE_STR", "LOSE_INT", "LOSE_WIS", "LOSE_DEX", "LOSE_CON",
                    "LOSE_ALL", "EXP_10", "EXP_20", "EXP_40", "EXP_80",
                    "DISENCHANT", "EAT_ITEM", "EAT_GOLD", "EAT_FOOD", "EAT_LIGHT",
                    "DRAIN_CHARGES", "SHATTER", "HALLU", "BLACK_BREATH"]
    for be in blow_effects:
        checks["melee " + be] = lambda m, be=be: any(
            (b.split(":") + ["", ""])[1] == be for b in m["blows"])
    for fl in ["INVISIBLE", "PASS_WALL", "KILL_WALL", "MULTIPLY"]:
        checks["flag " + fl] = lambda m, fl=fl: fl in m["flags"]
    for label, pred in checks.items():
        cands = [m for m in mons if pred(m)]
        if not cands:
            continue
        mm = min(cands, key=lambda m: (m["depth"], m["name"]))
        lines.append("| %s | %s | %d |" % (md(label), md(mm["name"]), mm["depth"]))
    lines.append("")
    write("A3-monster-spells.md", lines)


