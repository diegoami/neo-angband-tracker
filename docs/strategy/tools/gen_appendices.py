"""
Generate the data appendices of the Angband strategy manual directly from
lib/gamedata/*.txt, so the tables can never drift from the game data.

Usage (from the repository root):
    python3 docs/strategy/tools/gen_appendices.py

Writes docs/strategy/A1-...md .. A6-...md.
"""

import os
import re
import sys
from collections import OrderedDict, defaultdict

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
GD = os.path.join(ROOT, "lib", "gamedata")
OUT = os.path.join(ROOT, "docs", "strategy")

GEN_NOTE = ("> *Generated by `docs/strategy/tools/gen_appendices.py` from "
            "`lib/gamedata/{}`. Do not edit by hand; re-run the script instead.*\n")


# ---------------------------------------------------------------------------
# Generic record parser
# ---------------------------------------------------------------------------

def parse_records(fname, start_key="name"):
    """Return a list of records; each record is a list of (key, value)."""
    recs = []
    cur = None
    with open(os.path.join(GD, fname), encoding="utf-8") as f:
        for raw in f:
            line = raw.rstrip("\n")
            if not line or line.startswith("#"):
                continue
            if ":" not in line:
                continue
            key, val = line.split(":", 1)
            key = key.strip()
            if key == start_key:
                cur = [(key, val)]
                recs.append(cur)
            elif cur is not None:
                cur.append((key, val))
    return recs


def first(rec, key, default=None):
    for k, v in rec:
        if k == key:
            return v
    return default


def every(rec, key):
    return [v for k, v in rec if k == key]


def flags_of(rec, key="flags"):
    out = []
    for v in every(rec, key):
        out.extend(x.strip() for x in v.split("|") if x.strip())
    return out


def md(s):
    """Escape characters that break markdown tables."""
    return str(s).replace("|", "\\|").replace("*", "\\*").replace("_", "\\_")


# ---------------------------------------------------------------------------
# Expressions / dice (mirrors src/z-expression.c and src/z-dice.c closely
# enough for the forms used in the data files)
# ---------------------------------------------------------------------------

def c_div(a, b):
    q = abs(a) // abs(b)
    return q if (a >= 0) == (b >= 0) else -q


def eval_expr(base, ops):
    toks = ops.split()
    val = base
    i = 0
    while i < len(toks):
        op, n = toks[i], int(toks[i + 1])
        if op == "+":
            val += n
        elif op == "-":
            val -= n
        elif op == "*":
            val *= n
        elif op == "/":
            val = c_div(val, n)
        i += 2
    return val


def dice_range(dice, vars_):
    """Return (min, avg, max) for dice strings like '10+1d$S', '$Dd5', '20+$Dd5'."""
    s = dice
    for k, v in vars_.items():
        s = s.replace("$" + k, str(v))
    s = s.replace(" ", "")
    if re.fullmatch(r"-?\d+", s):
        v = int(s)
        return (v, v, v)
    m = re.fullmatch(r"(?:(-?\d+)\+)?(?:(\d+)d(\d+))?(?:M(\d+))?", s)
    if not m:
        return None
    base = int(m.group(1)) if m.group(1) else 0
    n = int(m.group(2)) if m.group(2) else 0
    sides = int(m.group(3)) if m.group(3) else 0
    if n <= 0 or sides <= 0:
        return (base, base, base)
    return (base + n, base + n * (sides + 1) / 2.0, base + n * sides)


