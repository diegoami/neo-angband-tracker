def gen_monsters(mons, mspells, projs, bases):
    lines = ["# Appendix A1 — Monster Compendium (non-unique monsters)\n",
             GEN_NOTE.format("monster.txt, monster_base.txt, monster_spell.txt"),
             "Every non-unique monster in the game, sorted by native depth (DL). "
             "Columns:\n",
             "* **Spd** — speed relative to normal (+10 = twice as many turns as a "
             "normal-speed character).",
             "* **HP** — *average* hit points (non-uniques are rolled with a normal "
             "distribution, std. dev. ≈ HP/8, see `mon_hp()` in `src/mon-make.c`).",
             "* **Blows** — melee attacks (`method effect dice`; plain damage shown "
             "without an effect).",
             "* **Spells** — `1_IN_x` is the chance per turn to cast; numbers in "
             "brackets are the **maximum damage** of that spell for this monster: "
             "breaths use `HP / divisor` capped (`breath_dam()` in `src/mon-spell.c`) "
             "computed at *average* HP, other spells use the monster's spell power "
             "(defaults to its depth).",
             "* **Imm/Vuln** — elemental immunities and vulnerabilities.",
             "* **Notes** — tactically relevant flags (inherited from the monster base "
             "as well); `groups` means it appears with friends.\n",
             "Use this table to answer *\"what can kill me on this level?\"* — scan the "
             "rows ±5 levels around your depth for big breath numbers, paralysis "
             "(`paralyze`), experience drain (`exp_*`), and stat drain.\n"]
    bands = [(0, 0), (1, 5), (6, 10), (11, 15), (16, 20), (21, 25), (26, 30),
             (31, 35), (36, 40), (41, 45), (46, 50), (51, 55), (56, 60),
             (61, 70), (71, 80), (81, 90), (91, 127)]
    nonu = [m for m in mons if "UNIQUE" not in m["flags"]]
    nonu.sort(key=lambda m: (m["depth"], m["name"]))
    lines.append("## Contents\n")
    for lo, hi in bands:
        label = "Town (DL0)" if hi == 0 else "DL%d–%d" % (lo, hi)
        lines.append("* [%s](#%s)" % (label, re.sub(r"[^a-z0-9]+", "-", label.lower()).strip("-")))
    lines.append("")
    for lo, hi in bands:
        label = "Town (DL0)" if hi == 0 else "DL%d–%d" % (lo, hi)
        rows = [m for m in nonu if lo <= m["depth"] <= hi]
        if not rows:
            continue
        lines.append("## %s\n" % label)
        lines.append("| DL | Monster | Sym | Spd | HP | AC | Exp | Blows | Spells | Imm/Vuln | Notes |")
        lines.append("|---:|---|:-:|---:|---:|---:|---:|---|---|---|---|")
        for m in rows:
            lines.append("| %d | %s | `%s` | %s | %d | %d | %d | %s | %s | %s | %s |" % (
                m["depth"], md(m["name"]), m["glyph"].replace("`", "'"),
                fmt_speed(m["speed"]), m["hp"], m["ac"], m["exp"],
                md(fmt_blows(m["blows"])), md(fmt_spells(m, mspells, projs)),
                md(fmt_defs(m)), md(fmt_notes(m))))
        lines.append("")

    # Monster bases summary
    lines.append("## Monster families (bases)\n")
    lines.append("| Base | Sym | # monsters | Depth range | Inherited flags |")
    lines.append("|---|:-:|---:|---|---|")
    by_base = defaultdict(list)
    for m in mons:
        by_base[m["base"]].append(m)
    for bname in sorted(by_base):
        ms = by_base[bname]
        b = bases.get(bname, {"glyph": "?", "flags": []})
        lines.append("| %s | `%s` | %d | %d–%d | %s |" % (
            md(bname), b["glyph"], len(ms), min(x["depth"] for x in ms),
            max(x["depth"] for x in ms), md(", ".join(b["flags"])) or "—"))
    lines.append("")
    write("A1-monster-compendium.md", lines)


