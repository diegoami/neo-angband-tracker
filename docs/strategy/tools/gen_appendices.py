def load_objects():
    recs = parse_records("object.txt")
    out = []
    for r in recs:
        effs = []
        cur = None
        for k, v in r:
            if k == "effect":
                cur = [v, None]
                effs.append(cur)
            elif k == "dice" and cur is not None:
                cur[1] = v
        out.append({
            "name": first(r, "name").replace("~", "").replace("&", "").strip(),
            "type": first(r, "type", ""),
            "level": first(r, "level", ""),
            "weight": first(r, "weight", "0"),
            "cost": first(r, "cost", ""),
            "alloc": first(r, "alloc", ""),
            "attack": first(r, "attack", ""),
            "armor": first(r, "armor", ""),
            "flags": flags_of(r),
            "values": every(r, "values"),
            "effects": effs,
            "time": first(r, "time", ""),
            "charges": first(r, "charges", ""),
            "power": first(r, "power", ""),
            "desc": " ".join(x.strip() for x in every(r, "desc")).strip(),
            "slays": every(r, "slay"), "brands": every(r, "brand"),
            "pval": first(r, "pval", ""),
        })
    return out


def fmt_weight(w):
    try:
        return "%.1f lb" % (int(w) / 10.0)
    except ValueError:
        return w


def fmt_alloc(a):
    if not a:
        return "not random"
    p = a.split(":")
    return "%s (%s)" % (p[1].replace(" to ", "–"), p[0]) if len(p) > 1 else a


def fmt_effects(effs):
    out = []
    for e, d in effs:
        s = e.replace(":", " ")
        if d:
            s += " " + d
        out.append(s)
    return "; ".join(out)


TVAL_ORDER = ["sword", "polearm", "hafted", "digger", "bow", "shot", "arrow", "bolt",
              "soft armor", "hard armor", "dragon armor", "shield", "cloak", "gloves",
              "boots", "helm", "crown", "light", "ring", "amulet", "potion", "scroll",
              "flask", "food", "mushroom", "wand", "staff", "rod", "magic book",
              "prayer book", "nature book", "shadow book", "chest"]


def gen_objects(objs):
    lines = ["# Appendix A6 — Object Kinds\n",
             GEN_NOTE.format("object.txt"),
             "All %d base object kinds. *Depth* is the allocation range and, in "
             "brackets, the commonness (higher = more common) from the `alloc:` "
             "line. Weights are in pounds. Weapon dice are base damage before "
             "multipliers; armour is base AC.\n" % len(objs)]
    by = defaultdict(list)
    for o in objs:
        by[o["type"]].append(o)
    order = TVAL_ORDER + sorted(t for t in by if t not in TVAL_ORDER)
    lines.append("## Contents\n")
    for t in order:
        if t in by:
            lines.append("* [%s](#%s)" % (t.title(), t.replace(" ", "-")))
    lines.append("")
    for t in order:
        if t not in by:
            continue
        rows = sorted(by[t], key=lambda o: (int(o["level"] or 0), o["name"]))
        lines.append("## %s\n" % t.title())
        if t in ("sword", "polearm", "hafted", "digger", "shot", "arrow", "bolt", "bow"):
            lines.append("| Name | Lvl | Depth | Dice / mult | Weight | Cost | Notes |")
            lines.append("|---|---:|---|---|---:|---:|---|")
            for o in rows:
                atk = o["attack"].split(":")[0] if o["attack"] else ""
                if t == "bow":
                    m = [v for v in o["values"] if "MIGHT" in v]
                    atk = "x" + (o["pval"] or "?")
                notes = ", ".join(o["flags"] + o["values"] + o["slays"] + o["brands"])
                lines.append("| %s | %s | %s | %s | %s | %s | %s |" % (
                    md(o["name"]), o["level"], fmt_alloc(o["alloc"]), atk,
                    fmt_weight(o["weight"]), o["cost"], md(notes) or "—"))
        elif t in ("soft armor", "hard armor", "dragon armor", "shield", "cloak",
                   "gloves", "boots", "helm", "crown"):
            lines.append("| Name | Lvl | Depth | AC | To-hit pen. | Weight | Cost | Notes |")
            lines.append("|---|---:|---|---:|---:|---:|---:|---|")
            for o in rows:
                ac = o["armor"].split(":")[0] if o["armor"] else ""
                tohit = o["attack"].split(":")[1] if o["attack"] and len(o["attack"].split(":")) > 1 else ""
                notes = ", ".join(o["flags"] + o["values"])
                if o["effects"]:
                    notes += (" | act: " if notes else "act: ") + fmt_effects(o["effects"])
                lines.append("| %s | %s | %s | %s | %s | %s | %s | %s |" % (
                    md(o["name"]), o["level"], fmt_alloc(o["alloc"]), ac, tohit,
                    fmt_weight(o["weight"]), o["cost"], md(notes) or "—"))
        else:
            lines.append("| Name | Lvl | Depth | Cost | Effect | Notes |")
            lines.append("|---|---:|---|---:|---|---|")
            for o in rows:
                notes = ", ".join(o["flags"] + o["values"])
                if o["charges"]:
                    notes += (", " if notes else "") + "charges " + o["charges"]
                if o["time"]:
                    notes += (", " if notes else "") + "recharge " + o["time"]
                lines.append("| %s | %s | %s | %s | %s | %s |" % (
                    md(o["name"]), o["level"], fmt_alloc(o["alloc"]), o["cost"],
                    md(fmt_effects(o["effects"])) or "—", md(notes) or "—"))
        lines.append("")
    write("A6-objects.md", lines)


