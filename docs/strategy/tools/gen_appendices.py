def load_projections():
    recs = parse_records("projection.txt", start_key="code")
    out = OrderedDict()
    for r in recs:
        code = first(r, "code")
        out[code] = {
            "name": first(r, "name", code),
            "type": first(r, "type", ""),
            "divisor": int(first(r, "divisor", "0") or 0),
            "cap": int(first(r, "damage-cap", "0") or 0),
            "num": (first(r, "numerator", "") or "").strip(),
            "den": (first(r, "denominator", "") or "").strip(),
        }
    return out


