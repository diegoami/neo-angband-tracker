DAMAGING = {"BOLT", "BALL", "BREATH", "DAMAGE", "ARC", "SHORT_BEAM", "BEAM",
            "LINE", "SPOT", "STAR", "STRIKE", "LASH", "SWARM", "BOLT_AWARE",
            "BOLT_STATUS", "BOLT_STATUS_DAM", "SPHERE"}


def load_monster_spells():
    recs = parse_records("monster_spell.txt")
    spells = OrderedDict()
    for r in recs:
        name = first(r, "name")
        effects = []      # list of dict(effect, dice, exprs)
        lores = []        # list of (upper_cutoff or None, lore)
        cur_lore = None
        for k, v in r:
            if k == "effect":
                effects.append({"effect": v, "dice": None, "expr": {}})
            elif k == "dice" and effects:
                effects[-1]["dice"] = v
            elif k == "expr" and effects:
                var, src, ops = v.split(":", 2)
                effects[-1]["expr"][var] = (src, ops)
            elif k == "lore":
                cur_lore = v
            elif k == "power-cutoff":
                lores.append((int(v), cur_lore))
                cur_lore = None
        if cur_lore is not None or not lores:
            lores.append((None, cur_lore))
        spells[name] = {
            "hit": first(r, "hit", ""),
            "effects": effects,
            "lores": lores,
        }
    return spells


def spell_lore(spell, power):
    lo = None
    for cutoff, lore in spell["lores"]:
        if cutoff is None or power <= cutoff:
            return lore or lo
        lo = lore
    return spell["lores"][-1][1]


def spell_damage(spell, power, hp, projs):
    """Return (kind, max_damage, avg_damage) or None for the first damaging effect."""
    for e in spell["effects"]:
        parts = e["effect"].split(":")
        etype = parts[0]
        if etype == "BREATH":
            elem = parts[1]
            p = projs.get(elem)
            if not p or not p["divisor"]:
                return None
            dam = hp // p["divisor"]
            if p["cap"] and dam > p["cap"]:
                dam = p["cap"]
            return ("breath", dam, dam)
        if etype in DAMAGING and e["dice"]:
            vars_ = {}
            for var, (src, ops) in e["expr"].items():
                if src == "SPELL_POWER":
                    vars_[var] = eval_expr(power, ops)
                elif src == "MAX_SIGHT":
                    vars_[var] = eval_expr(20, ops)
            rng = dice_range(e["dice"], vars_)
            if rng:
                return (etype.lower(), rng[2], rng[1])
    return None


